function assert(condition, message) {
  if (!condition) throw new Error(message)
}

const guSlugMap = JSON.parse(await readFile(path.join(projectRoot, 'scripts/gu-slug-map.json'), 'utf8'))

function slugFor(name) {
  const slug = guSlugMap[name]
  if (!slug) throw new Error(`scripts/gu-slug-map.json 缺少「${name}」的拼音 slug`)
  return slug
}

const volumeChapters = corpusIndex.chapters.filter((chapter) => chapter.volumeId === 1)
const chapterText = new Map()
for (const chapter of volumeChapters) {
  chapterText.set(chapter.id, await readFile(path.join(projectRoot, 'corpus', chapter.file), 'utf8'))
}

const existingFiles = (await readdir(guRoot)).filter((file) => file.endsWith('.json'))
const existingEntities = await Promise.all(
  existingFiles.map(async (file) => JSON.parse(await readFile(path.join(guRoot, file), 'utf8'))),
)
const manualEntities = existingEntities.filter((entity) => entity.attributes?.审计批次 !== '第一卷蛊虫全面复核')
const existingNames = new Set(manualEntities.map((entity) => entity.name))

const auditedNames = new Set()
const generated = []
for (const [name, aliases, rank, category, recordKind, sources, summary] of auditedGu) {
  assert(!auditedNames.has(name), `审计表包含重复蛊名：${name}`)
  auditedNames.add(name)
  assert(sources.every((chapterId) => chapterText.has(chapterId)), `${name}: 证据章节超出第一卷`)

  const searchableNames = [name, ...aliases]
  for (const chapterId of sources) {
    const text = chapterText.get(chapterId)
    assert(searchableNames.some((candidate) => text.includes(candidate)), `${name}: 第 ${chapterId} 节未找到名称或别名`)
  }

  if (existingNames.has(name)) continue

  const firstChapter = volumeChapters.find((chapter) => {
    const text = chapterText.get(chapter.id)
    return searchableNames.some((candidate) => text.includes(candidate))
  })
  assert(firstChapter, `${name}: 第一卷未找到首次提及`)

  const slug = slugFor(name)
  generated.push({
    file: `${slug}.json`,
    entity: {
      schemaVersion: 1,
      id: `gu.${slug}`,
      type: 'gu',
      name,
      aliases,
      summary,
      status: 'verified-volume-1',
      scope: { volume: 1, maxChapter: 199 },
      attributes: {
        品阶: rank,
        类别: category,
        第一卷记录形态: recordKind,
        审计批次: '第一卷蛊虫全面复核',
      },
      facts: [{ text: summary, sources }],
      relations: [],
      tags: [rank, category, recordKind, '第一卷'].filter((tag, index, all) => all.indexOf(tag) === index),
      firstMention: { chapterId: firstChapter.id },
    },
  })
}

